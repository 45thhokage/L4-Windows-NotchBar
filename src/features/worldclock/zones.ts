/** Display label for a zone: Apple label first, then the country entry's city. */
export function cityFor(zone: string): string {
  return (
    APPLE_CITIES.find((c) => c.zone === zone)?.city ??
    ZONE_ENTRIES.find((c) => c.zone === zone)?.city ??
    zone
  );
}

/** Entries not yet added, matching the query in country, city or zone. */
export function searchZones(query: string, added: string[]): ZoneEntry[] {
  const q = query.trim().toLowerCase();
  return ZONE_ENTRIES.filter((e) => {
    if (added.includes(e.zone)) return false;
    if (!q) return false;
    return (
      e.country.toLowerCase().includes(q) ||
      e.city.toLowerCase().includes(q) ||
      e.zone.toLowerCase().includes(q)
    );
  });
}
